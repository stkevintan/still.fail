#!/usr/bin/env node
// Direct Pion asset generator for `pion/ui/packages/sf_assets_native/`.
// Bypasses `mbt2pion` so ~2 MB raw `.mbt` asset blobs are emitted directly as clean Pion.
//
// Reads from `libs/ui/src/controls/` (read-only):
//   - font_assets.mbt  (300,144 B TTF, sha256 3cfafa86...)
//   - math_glyphs.mbt  (293,607 B gzipped outlines, sha256 7fdd1b48...)
//   - icon_data.mbt    (24-grid stroke table)
//   - palette_data.mbt (web_light / web_dark palettes)
//   - math.json & math-mac.textrec (pre-build test fixtures)

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const SCRIPT_DIR = path.dirname(new URL(import.meta.url).pathname);
const REPO_ROOT = path.resolve(SCRIPT_DIR, '../../..');
const CONTROLS_DIR = path.join(REPO_ROOT, 'libs/ui/src/controls');
const OUT_SRC = path.join(REPO_ROOT, 'pion/ui/packages/sf_assets_native/src');

const EXPECTED_TTF_LEN = 300144;
const EXPECTED_TTF_SHA = '3cfafa86e28b87184d592fef82846e8c10cb48653c62efcda34f082da225ec34';
const EXPECTED_MATH_LEN = 293607;
const EXPECTED_MATH_SHA = '7fdd1b483df973987efc5d9731fc09d348e71346905604ed2f48ffdc295814f4';
const EXPECTED_MATH_JSON_LEN = 15052;
const EXPECTED_MATH_JSON_SHA = '7398fa93cdd39be955d010c31728cb64979db94a89ad3f8fc8fe6ab97b11d13f';
const EXPECTED_MATH_TEXTREC_LEN = 5363;
const EXPECTED_MATH_TEXTREC_SHA = 'eb3197183f1252d7382e30e4e1b20022f7111664f023421a3e844ae88faa2cc1';

function sha256Hex(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

function decodeMbtBytesLiteral(filePath) {
  const src = fs.readFileSync(filePath, 'utf8');
  const m = src.match(/b"((?:[^"\\]|\\.)*)"/s);
  if (!m) throw new Error(`No b"..." literal found in ${filePath}`);
  const raw = m[1];
  const bytes = [];
  for (let i = 0; i < raw.length; i++) {
    if (raw[i] === '\\') {
      const n = raw[i + 1];
      if (n === 'x') {
        bytes.push(parseInt(raw.slice(i + 2, i + 4), 16));
        i += 3;
      } else if (n === 'n') {
        bytes.push(10); i++;
      } else if (n === 'r') {
        bytes.push(13); i++;
      } else if (n === 't') {
        bytes.push(9); i++;
      } else if (n === '\\') {
        bytes.push(92); i++;
      } else if (n === '"') {
        bytes.push(34); i++;
      } else if (n === '\'') {
        bytes.push(39); i++;
      } else {
        throw new Error(`Unknown escape \\${n} in ${filePath}`);
      }
    } else {
      bytes.push(raw.charCodeAt(i));
    }
  }
  return Buffer.from(bytes);
}

function emitBase64PionModule(fnName, comment, buf, sha) {
  const b64 = buf.toString('base64');
  // Split into 16 KB string chunks so pionc formats and compiles quickly.
  const chunkSize = 16384;
  const chunks = [];
  for (let i = 0; i < b64.length; i += chunkSize) {
    chunks.push(b64.slice(i, i + chunkSize));
  }
  const lines = [];
  lines.push(`// Generated by pion/tools/mbt2pion-monoid/gen_assets.mjs — DO NOT HAND-EDIT.`);
  lines.push(`// ${comment}`);
  lines.push(`// Decoded length: ${buf.length} bytes | SHA-256: ${sha}`);
  lines.push('');
  lines.push('import "base64"');
  lines.push('');
  lines.push(`pub fn ${fnName}() -> Bytes {`);
  lines.push('  let sb = StringBuilder::new()');
  for (const ch of chunks) {
    lines.push(`  sb.write_string("${ch}")`);
  }
  lines.push('  match base64::decode(sb.to_string()) {');
  lines.push('    Ok(b) => b');
  lines.push('    Err(_) => "".to_bytes()');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitIconDataPion() {
  const src = fs.readFileSync(path.join(CONTROLS_DIR, 'icon_data.mbt'), 'utf8');
  const entries = [];
  const re = /^\s*"([^"]+)":\s*"([^"]*)",?\s*$/gm;
  let m;
  while ((m = re.exec(src)) !== null) {
    entries.push([m[1], m[2]]);
  }
  if (entries.length < 50) {
    throw new Error(`Unexpectedly few icons parsed from icon_data.mbt: ${entries.length}`);
  }
  const lines = [];
  lines.push('// Generated by pion/tools/mbt2pion-monoid/gen_assets.mjs from libs/ui/src/controls/icon_data.mbt — DO NOT HAND-EDIT.');
  lines.push(`// Total icons: ${entries.length}`);
  lines.push('');
  lines.push('pub fn icon_data() -> Map[String, String] {');
  lines.push('  let m : Map[String, String] = Map::new()');
  for (const [k, v] of entries) {
    lines.push(`  m.set("${k}", "${v}")`);
  }
  lines.push('  m');
  lines.push('}');
  lines.push('');
  return { code: lines.join('\n'), count: entries.length };
}

function emitPaletteDataPion() {
  const src = fs.readFileSync(path.join(CONTROLS_DIR, 'palette_data.mbt'), 'utf8');
  function extractBlock(name) {
    const re = new RegExp(`let\\s+${name}\\s*:\\s*Palette\\s*=\\s*\\{([\\s\\S]*?)\\n\\}`);
    const m = src.match(re);
    if (!m) throw new Error(`Could not find ${name} in palette_data.mbt`);
    const body = m[1]
      .replace(/\balpha\(/g, 'sf::palette_alpha(')
      .split('\n')
      .map(l => l.trim())
      .filter(Boolean)
      .map(l => `    ${l}`)
      .join('\n');
    return body;
  }
  const lightBody = extractBlock('web_light');
  const darkBody = extractBlock('web_dark');
  const lines = [];
  lines.push('// Generated by pion/tools/mbt2pion-monoid/gen_assets.mjs from libs/ui/src/controls/palette_data.mbt — DO NOT HAND-EDIT.');
  lines.push('');
  lines.push('import "sf"');
  lines.push('');
  lines.push('let tone_light : Double = 0.18');
  lines.push('');
  lines.push('let tone_dark : Double = 0.16');
  lines.push('');
  lines.push('pub fn web_light_palette() -> sf::Palette {');
  lines.push('  sf::Palette::{');
  lines.push(lightBody);
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('pub fn web_dark_palette() -> sf::Palette {');
  lines.push('  sf::Palette::{');
  lines.push(darkBody);
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitNativeAssetsEntry() {
  return [
    '// Native/headless asset profile installer for `sf`.',
    '',
    'import "sf"',
    '',
    'pub fn install_native_assets() -> Unit {',
    '  sf::register_faces(code_face_ttf)',
    '  sf::register_math_glyphs(math_glyphs_gz, fn() -> Unit { () })',
    '  sf::register_icons(icon_data())',
    '  sf::register_palettes(web_light_palette(), web_dark_palette())',
    '}',
    '',
  ].join('\n');
}

function main() {
  const checkMode = process.argv.includes('--check');

  const ttf = decodeMbtBytesLiteral(path.join(CONTROLS_DIR, 'font_assets.mbt'));
  const ttfSha = sha256Hex(ttf);
  if (ttf.length !== EXPECTED_TTF_LEN || ttfSha !== EXPECTED_TTF_SHA) {
    throw new Error(`TTF mismatch: len=${ttf.length} sha=${ttfSha}`);
  }

  const mathGz = decodeMbtBytesLiteral(path.join(CONTROLS_DIR, 'math_glyphs.mbt'));
  const mathSha = sha256Hex(mathGz);
  if (mathGz.length !== EXPECTED_MATH_LEN || mathSha !== EXPECTED_MATH_SHA) {
    throw new Error(`Math glyphs mismatch: len=${mathGz.length} sha=${mathSha}`);
  }

  const mathJson = fs.readFileSync(path.join(CONTROLS_DIR, 'math.json'));
  const mathJsonSha = sha256Hex(mathJson);
  if (mathJson.length !== EXPECTED_MATH_JSON_LEN || mathJsonSha !== EXPECTED_MATH_JSON_SHA) {
    throw new Error(`math.json mismatch: len=${mathJson.length} sha=${mathJsonSha}`);
  }

  const mathTextrec = fs.readFileSync(path.join(CONTROLS_DIR, 'math-mac.textrec'));
  const mathTextrecSha = sha256Hex(mathTextrec);
  if (mathTextrec.length !== EXPECTED_MATH_TEXTREC_LEN || mathTextrecSha !== EXPECTED_MATH_TEXTREC_SHA) {
    throw new Error(`math-mac.textrec mismatch: len=${mathTextrec.length} sha=${mathTextrecSha}`);
  }

  const icons = emitIconDataPion();

  // Emit pre-build test fixtures (excluded from production build via _test.pion suffix)
  const fixturesCode = [
    '// Generated pre-build test fixtures from libs/ui/src/controls/{math.json,math-mac.textrec}.',
    '',
    'import "base64"',
    '',
    'fn decode_fixture(b64 : String) -> Bytes {',
    '  match base64::decode(b64) {',
    '    Ok(b) => b',
    '    Err(_) => "".to_bytes()',
    '  }',
    '}',
    '',
    'fn math_json_fixture_bytes() -> Bytes {',
    `  decode_fixture("${mathJson.toString('base64')}")`,
    '}',
    '',
    'fn math_textrec_fixture_bytes() -> Bytes {',
    `  decode_fixture("${mathTextrec.toString('base64')}")`,
    '}',
    '',
  ].join('\n');

  const expectedFiles = [
    ['font_assets.pion', emitBase64PionModule('code_face_ttf', 'JetBrains Mono TTF (libs/ui/src/controls/font_assets.mbt)', ttf, ttfSha)],
    ['math_glyphs.pion', emitBase64PionModule('math_glyphs_gz', 'Gzipped math glyph outlines (libs/ui/src/controls/math_glyphs.mbt)', mathGz, mathSha)],
    ['icon_data.pion', icons.code],
    ['palette_data.pion', emitPaletteDataPion()],
    ['native_assets.pion', emitNativeAssetsEntry()],
    ['fixtures_test.pion', fixturesCode],
  ];

  if (checkMode) {
    let mismatches = 0;
    for (const [name, expected] of expectedFiles) {
      const targetPath = path.join(OUT_SRC, name);
      if (!fs.existsSync(targetPath)) {
        console.error(`gen_assets.mjs --check: missing file ${targetPath}`);
        mismatches++;
        continue;
      }
      const actual = fs.readFileSync(targetPath);
      const expBuf = Buffer.from(expected, 'utf8');
      if (!actual.equals(expBuf)) {
        console.error(`gen_assets.mjs --check: byte mismatch in ${name} (actual=${actual.length} B, expected=${expBuf.length} B)`);
        mismatches++;
      }
    }
    if (mismatches > 0) {
      console.error(`gen_assets.mjs --check: FAILED (${mismatches} file(s) out of sync; run node pion/tools/mbt2pion-monoid/gen_assets.mjs)`);
      process.exit(1);
    }
    console.log(`OK: gen_assets.mjs --check verified all ${expectedFiles.length} asset files (${icons.count} icons)`);
    return;
  }

  fs.mkdirSync(OUT_SRC, { recursive: true });
  for (const [name, content] of expectedFiles) {
    fs.writeFileSync(path.join(OUT_SRC, name), content);
  }

  console.log(`Generated sf_assets_native:`);
  console.log(`  code_face_ttf:     ${ttf.length} B (sha256 ${ttfSha})`);
  console.log(`  math_glyphs_gz:    ${mathGz.length} B (sha256 ${mathSha})`);
  console.log(`  icon_data:         ${icons.count} icons`);
  console.log(`  palette_data:      web_light + web_dark`);
  console.log(`  math.json:         ${mathJson.length} B (sha256 ${mathJsonSha})`);
  console.log(`  math-mac.textrec:  ${mathTextrec.length} B (sha256 ${mathTextrecSha})`);
}

main();
